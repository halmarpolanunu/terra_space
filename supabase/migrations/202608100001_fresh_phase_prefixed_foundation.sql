-- =====================================================================================
-- 10. Row Level Security
-- =====================================================================================
--
-- Every new table has RLS turned on and no policies at all. The service role used by the
-- backend and by n8n bypasses RLS, so the local system keeps working; the browser-facing
-- anon and authenticated keys match no policy and therefore see nothing. This keeps
-- source text, events, and settings away from any browser client.

alter table public.phase1_sources             enable row level security;
alter table public.phase1_attachments         enable row level security;
alter table public.phase1_processing_runs     enable row level security;
alter table public.phase2_event_candidates    enable row level security;
alter table public.phase2_candidate_runs      enable row level security;
alter table public.phase3_event_types         enable row level security;
alter table public.phase3_taxonomy_nodes      enable row level security;
alter table public.phase3_actors              enable row level security;
alter table public.phase3_actor_aliases       enable row level security;
alter table public.phase3_locations           enable row level security;
alter table public.phase3_location_gazetteer  enable row level security;
alter table public.phase3_events              enable row level security;
alter table public.phase3_event_runs          enable row level security;
alter table public.phase3_event_sources       enable row level security;
alter table public.phase3_event_actors        enable row level security;
alter table public.phase3_event_locations     enable row level security;
alter table public.phase3_duplicate_flags     enable row level security;
alter table public.app_settings               enable row level security;

-- Supabase hands the browser-facing anon and authenticated roles a SELECT grant on every
-- new table in the public schema by default. RLS already blocks the rows, but the grant
-- alone still leaks the table and column names through the auto-generated GraphQL schema.
-- Nothing in Terra Space uses those two roles, so take the grant away entirely.
do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'phase1_sources', 'phase1_attachments', 'phase1_processing_runs',
    'phase2_event_candidates', 'phase2_candidate_runs',
    'phase3_event_types', 'phase3_taxonomy_nodes', 'phase3_actors', 'phase3_actor_aliases',
    'phase3_locations', 'phase3_location_gazetteer',
    'phase3_events', 'phase3_event_runs', 'phase3_event_sources', 'phase3_event_actors',
    'phase3_event_locations', 'phase3_duplicate_flags',
    'app_settings'
  ] loop
    execute format('revoke all on table public.%I from anon, authenticated', v_table);
  end loop;
end;
$$;


