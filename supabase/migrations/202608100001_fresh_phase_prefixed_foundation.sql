-- Fresh Phase-Prefixed Supabase Foundation
--
-- Creates the shared local PostgreSQL schema that becomes the single source of truth for
-- Terra Space and the four n8n workflows. See:
--   project-knowledge/decisions/Fresh-Phase-Prefixed-Supabase-Architecture.md
--   project-knowledge/plans/2026-08-10-fresh-supabase-foundation.md
--
-- Safety rules honoured by this file:
--   * It only creates new objects. It never drops, truncates, renames, or deletes an existing
--     table, column, or row.
--   * Every new table name carries a literal phase1_ / phase2_ / phase3_ prefix, except
--     app_settings, which genuinely serves every phase.
--   * Every statement is written to be safe to run twice.
--
-- Sections:
--   1. Shared helper (updated_at trigger function)
--   2. Phase 1 tables - collect and clean sources
--   3. Phase 2 tables - detect event candidates
--   4. Phase 3 reference tables - event types, taxonomy, actors, locations, gazetteer
--   5. Phase 3 authoritative event tables and relationships
--   6. Application-wide settings
--   7. Indexes
--   8. updated_at triggers
--   9. Authority function: phase3_create_pipeline_event
--  10. Row Level Security
--  11. Plain-language table and column comments


-- =====================================================================================
-- 1. Shared helper
-- =====================================================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

comment on function public.set_updated_at() is
  'Trigger helper. Stamps updated_at with the current time whenever a row is changed.';


