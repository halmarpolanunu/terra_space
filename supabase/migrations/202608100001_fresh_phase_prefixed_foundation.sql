create table if not exists public.phase3_event_types (
  id           uuid primary key default gen_random_uuid(),
  name         text not null unique,
  description  text not null,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.phase3_taxonomy_nodes (
  id             uuid primary key default gen_random_uuid(),
  name           text not null,
  description    text,
  level          text not null
                   constraint phase3_taxonomy_nodes_level_check
                   check (level in ('domain', 'category', 'subcategory', 'event_type')),
  parent_id      uuid references public.phase3_taxonomy_nodes (id) on delete restrict,
  event_type_id  uuid unique references public.phase3_event_types (id) on delete set null,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint phase3_taxonomy_nodes_domain_is_root
    check ((level = 'domain') = (parent_id is null)),
  constraint phase3_taxonomy_nodes_only_leaf_carries_event_type
    check (level = 'event_type' or event_type_id is null)
);

-- Sibling names must be unique. Two indexes are needed because domains have no parent and
-- PostgreSQL treats each NULL parent_id as distinct inside a plain unique constraint.
create unique index if not exists phase3_taxonomy_nodes_unique_child_name
  on public.phase3_taxonomy_nodes (parent_id, lower(name))
  where parent_id is not null;

create unique index if not exists phase3_taxonomy_nodes_unique_domain_name
  on public.phase3_taxonomy_nodes (lower(name))
  where parent_id is null;

create table if not exists public.phase3_actors (
  id          uuid primary key default gen_random_uuid(),
  name        text not null unique,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.phase3_actor_aliases (
  id          uuid primary key default gen_random_uuid(),
  actor_id    uuid not null references public.phase3_actors (id) on delete cascade,
  alias       text not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint phase3_actor_aliases_unique_alias unique (actor_id, alias)
);

create table if not exists public.phase3_locations (
  id                    uuid primary key default gen_random_uuid(),
  country_iso3          text
                          constraint phase3_locations_country_iso3_check
                          check (country_iso3 is null or country_iso3 ~ '^[A-Z]{3}$'),
  admin1                text,
  city_regency          text,
  latitude              numeric(9,6)
                          constraint phase3_locations_latitude_check
                          check (latitude is null or (latitude >= -90 and latitude <= 90)),
  longitude             numeric(9,6)
                          constraint phase3_locations_longitude_check
                          check (longitude is null or (longitude >= -180 and longitude <= 180)),
  coordinate_precision  text
                          constraint phase3_locations_coordinate_precision_check
                          check (coordinate_precision is null
                                 or coordinate_precision in ('country', 'admin1', 'city_regency')),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

-- One row per distinct place, so events can share locations instead of duplicating them.
create unique index if not exists phase3_locations_unique_place
  on public.phase3_locations (
    coalesce(country_iso3, ''),
    coalesce(lower(admin1), ''),
    coalesce(lower(city_regency), '')
  );

create table if not exists public.phase3_location_gazetteer (
  lookup_key            text primary key,
  country_iso3          text not null
                          constraint phase3_location_gazetteer_country_iso3_check
                          check (country_iso3 ~ '^[A-Z]{3}$'),
  admin1                text,
  city_regency          text,
  latitude              numeric(9,6) not null
                          constraint phase3_location_gazetteer_latitude_check
                          check (latitude >= -90 and latitude <= 90),
  longitude             numeric(9,6) not null
                          constraint phase3_location_gazetteer_longitude_check
                          check (longitude >= -180 and longitude <= 180),
  coordinate_precision  text not null
                          constraint phase3_location_gazetteer_coordinate_precision_check
                          check (coordinate_precision in ('country', 'admin1', 'city_regency'))
);


