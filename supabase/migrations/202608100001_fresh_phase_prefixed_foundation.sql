                      check (resolution in ('pending', 'kept_separate', 'linked')),
  resolved_at       timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint phase3_duplicate_flags_not_self check (event_id <> matched_event_id),
  constraint phase3_duplicate_flags_unique_pair unique (event_id, matched_event_id)
