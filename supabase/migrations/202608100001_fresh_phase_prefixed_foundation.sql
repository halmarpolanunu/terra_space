-- =====================================================================================
-- 9. Authority function: phase3_create_pipeline_event
-- =====================================================================================
--
-- This is the ONLY way the n8n pipeline is allowed to create an authoritative event.
-- It exists so that the rules from the approved architecture live in the database itself
-- rather than in workflow nodes that are easy to change by accident:
--
--   * A missing candidate key or Phase 1 source is rejected outright.
--   * A candidate key that already has an event returns that event's id and changes nothing.
--     A later pipeline run may add audit history, but may never overwrite the authoritative
--     event and may never touch the owner's edits.
--   * FINAL becomes a published event; EXCEPTION becomes a hidden one.
--   * The complete candidate JSON and the complete Phase 3 event JSON are stored as-is.
--   * Sources, actors and locations are linked only when the event is newly created.
--   * human_modified_at and human_modified_fields are never written here.
--
-- Expected payload shape (unknown or unusable values are stored as blank, never guessed):
--
--   {
--     "candidate_key":        "text, required",
--     "phase1_source_id":     "uuid, required",
--     "pipeline_outcome":     "FINAL | EXCEPTION, required",
--     "title":                "text (falls back to candidate.working_title)",
--     "summary":              "text (falls back to candidate.summary)",
--     "event_date":           "text, optional",
--     "event_date_precision": "exact | month | year | unknown, optional",
--     "epistemic_status":     "confirmed | reported | alleged | planned | denied | unknown",
--     "event_type_id":        "uuid, optional",
--     "event_type_name":      "text, optional - matched against active event types only",
--     "processed_at":         "timestamptz, optional (defaults to now)",
--     "reference_label":      "text, optional",
--     "evidence_quote":       "text, optional",
--     "candidate":            { ...full Phase 2 candidate... },
--     "event_snapshot":       { ...full Phase 3 event record... },
--     "actors":               [ { "name": "text", "role": "source" | "target" } ],
--     "locations":            [ { "country_iso3": "UKR", "admin1": null,
--                                 "city_regency": "kharkiv", "latitude": 0, "longitude": 0,
--                                 "coordinate_precision": "city_regency" } ]
--   }

create or replace function public.phase3_create_pipeline_event(payload jsonb)
returns uuid
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_candidate_key  text;
  v_source_text    text;
  v_source_id      uuid;
  v_outcome        text;
  v_status         text;
  v_title          text;
  v_summary        text;
  v_epistemic      text;
  v_precision      text;
  v_event_type_id  uuid;
  v_type_text      text;
  v_processed_text text;
  v_processed_at   timestamptz;
  v_event_id       uuid;
  v_candidate      jsonb;
  v_snapshot       jsonb;
  v_actors         jsonb;
  v_locations      jsonb;
  v_actor          jsonb;
  v_actor_id       uuid;
  v_actor_name     text;
  v_actor_role     text;
  v_location       jsonb;
  v_location_id    uuid;
  v_country        text;
  v_admin1         text;
  v_city           text;
  v_latitude       numeric;
  v_longitude      numeric;
  v_coord_prec     text;
begin
  if payload is null or jsonb_typeof(payload) <> 'object' then
    raise exception 'phase3_create_pipeline_event: payload must be a JSON object.'
      using errcode = '22023';
  end if;

  -- ---- required identity -------------------------------------------------------------
  v_candidate_key := nullif(btrim(coalesce(payload ->> 'candidate_key', '')), '');
  if v_candidate_key is null then
    raise exception 'phase3_create_pipeline_event: candidate_key is required.'
      using errcode = '22023';
  end if;

  v_source_text := nullif(btrim(coalesce(payload ->> 'phase1_source_id', '')), '');
  if v_source_text is null then
    raise exception 'phase3_create_pipeline_event: phase1_source_id is required.'
      using errcode = '22023';
  end if;
  begin
    v_source_id := v_source_text::uuid;
  exception
    when invalid_text_representation then
      raise exception 'phase3_create_pipeline_event: phase1_source_id "%" is not a valid UUID.',
        v_source_text using errcode = '22023';
  end;

  if not exists (select 1 from public.phase1_sources where id = v_source_id) then
    raise exception 'phase3_create_pipeline_event: Phase 1 source % does not exist.', v_source_id
      using errcode = '23503';
  end if;

  v_outcome := upper(btrim(coalesce(payload ->> 'pipeline_outcome', '')));
  if v_outcome not in ('FINAL', 'EXCEPTION') then
    raise exception 'phase3_create_pipeline_event: pipeline_outcome must be FINAL or EXCEPTION, got "%".',
      coalesce(payload ->> 'pipeline_outcome', '') using errcode = '22023';
  end if;

  -- ---- already authoritative: return it untouched --------------------------------------
  select id into v_event_id
    from public.phase3_events
   where candidate_key = v_candidate_key;
  if v_event_id is not null then
    return v_event_id;
  end if;

  -- ---- normalise the rest of the payload ------------------------------------------------
  v_candidate := case when jsonb_typeof(payload -> 'candidate') = 'object'
                      then payload -> 'candidate' else null end;
  v_snapshot  := case when jsonb_typeof(payload -> 'event_snapshot') = 'object'
                      then payload -> 'event_snapshot' else null end;

  v_title := coalesce(
    nullif(btrim(coalesce(payload ->> 'title', '')), ''),
    nullif(btrim(coalesce(v_candidate ->> 'working_title', '')), '')
  );
  if v_title is null then
    raise exception 'phase3_create_pipeline_event: a title is required (payload.title or candidate.working_title).'
      using errcode = '22023';
  end if;

  v_summary := coalesce(
    nullif(btrim(coalesce(payload ->> 'summary', '')), ''),
    nullif(btrim(coalesce(v_candidate ->> 'summary', '')), '')
  );
  if v_summary is null then
    raise exception 'phase3_create_pipeline_event: a summary is required (payload.summary or candidate.summary).'
      using errcode = '22023';
  end if;

  -- Pipeline epistemic values arrive in upper case. Anything unrecognised becomes
  -- "unknown" rather than a guess.
  v_epistemic := lower(btrim(coalesce(payload ->> 'epistemic_status', '')));
  if v_epistemic not in ('confirmed', 'reported', 'alleged', 'planned', 'denied', 'unknown') then
    v_epistemic := 'unknown';
  end if;

  v_precision := lower(btrim(coalesce(payload ->> 'event_date_precision', '')));
  if v_precision not in ('exact', 'month', 'year', 'unknown') then
    v_precision := null;
  end if;

  -- Closed taxonomy: match an ACTIVE event type or leave the type blank. Never create one.
  v_event_type_id := null;
  v_type_text := nullif(btrim(coalesce(payload ->> 'event_type_id', '')), '');
  if v_type_text is not null then
    begin
      select id into v_event_type_id
        from public.phase3_event_types
       where id = v_type_text::uuid and is_active;
    exception
      when invalid_text_representation then
        v_event_type_id := null;
    end;
  end if;
  if v_event_type_id is null then
    v_type_text := nullif(btrim(coalesce(payload ->> 'event_type_name', '')), '');
    if v_type_text is not null then
      select id into v_event_type_id
        from public.phase3_event_types
       where is_active and lower(btrim(name)) = lower(v_type_text)
       limit 1;
    end if;
  end if;

  v_processed_text := nullif(btrim(coalesce(payload ->> 'processed_at', '')), '');
  begin
    v_processed_at := coalesce(v_processed_text::timestamptz, now());
  exception
    when others then
      v_processed_at := now();
  end;

  v_status := case v_outcome when 'FINAL' then 'published' else 'hidden' end;

  -- ---- create the authoritative event ---------------------------------------------------
  insert into public.phase3_events (
    candidate_key, phase1_source_id, origin, pipeline_outcome, dashboard_status,
    title, summary, event_date, event_date_precision, epistemic_status, event_type_id,
    pipeline_candidate, pipeline_event_snapshot, pipeline_first_seen_at, published_at
  )
  values (
    v_candidate_key, v_source_id, 'pipeline', v_outcome, v_status,
    v_title, v_summary,
    nullif(btrim(coalesce(payload ->> 'event_date', '')), ''),
    v_precision, v_epistemic, v_event_type_id,
    v_candidate, v_snapshot, v_processed_at,
    case when v_status = 'published' then v_processed_at else null end
  )
  on conflict (candidate_key) do nothing
  returning id into v_event_id;

  if v_event_id is null then
    -- Another call created the same candidate key first. Return that one unchanged.
    select id into v_event_id
      from public.phase3_events
     where candidate_key = v_candidate_key;
    return v_event_id;
  end if;

  -- ---- link the Phase 1 source and its evidence -----------------------------------------
  insert into public.phase3_event_sources (event_id, phase1_source_id, reference_label, evidence_quote)
  values (
    v_event_id,
    v_source_id,
    coalesce(nullif(btrim(coalesce(payload ->> 'reference_label', '')), ''), 'Phase 1 source'),
    nullif(btrim(coalesce(payload ->> 'evidence_quote', '')), '')
  )
  on conflict do nothing;

  -- ---- actors ----------------------------------------------------------------------------
  v_actors := case when jsonb_typeof(payload -> 'actors') = 'array'
                   then payload -> 'actors' else '[]'::jsonb end;
  for v_actor in select value from jsonb_array_elements(v_actors)
  loop
    continue when jsonb_typeof(v_actor) <> 'object';
    v_actor_name := nullif(btrim(coalesce(v_actor ->> 'name', '')), '');
    v_actor_role := lower(btrim(coalesce(v_actor ->> 'role', '')));
    continue when v_actor_name is null or v_actor_role not in ('source', 'target');

    insert into public.phase3_actors (name) values (v_actor_name)
    on conflict (name) do nothing;

    select id into v_actor_id from public.phase3_actors where name = v_actor_name;

    insert into public.phase3_event_actors (event_id, actor_id, role)
    values (v_event_id, v_actor_id, v_actor_role)
    on conflict do nothing;
  end loop;

  -- ---- locations --------------------------------------------------------------------------
  v_locations := case when jsonb_typeof(payload -> 'locations') = 'array'
                      then payload -> 'locations' else '[]'::jsonb end;
  for v_location in select value from jsonb_array_elements(v_locations)
  loop
    continue when jsonb_typeof(v_location) <> 'object';

    v_country := upper(nullif(btrim(coalesce(v_location ->> 'country_iso3', '')), ''));
    if v_country is not null and v_country !~ '^[A-Z]{3}$' then
      v_country := null;
    end if;
    v_admin1 := nullif(btrim(coalesce(v_location ->> 'admin1', '')), '');
    v_city   := nullif(btrim(coalesce(v_location ->> 'city_regency', '')), '');
    continue when v_country is null and v_admin1 is null and v_city is null;

    v_latitude := case when coalesce(v_location ->> 'latitude', '') ~ '^-?[0-9]+(\.[0-9]+)?$'
                       then (v_location ->> 'latitude')::numeric else null end;
    v_longitude := case when coalesce(v_location ->> 'longitude', '') ~ '^-?[0-9]+(\.[0-9]+)?$'
                        then (v_location ->> 'longitude')::numeric else null end;
    if v_latitude is null or v_longitude is null
       or v_latitude < -90 or v_latitude > 90
       or v_longitude < -180 or v_longitude > 180 then
      v_latitude := null;
      v_longitude := null;
    end if;

    v_coord_prec := lower(btrim(coalesce(v_location ->> 'coordinate_precision', '')));
    if v_coord_prec not in ('country', 'admin1', 'city_regency') then
      v_coord_prec := null;
    end if;

    select id into v_location_id
      from public.phase3_locations
     where coalesce(country_iso3, '') = coalesce(v_country, '')
       and coalesce(lower(admin1), '') = coalesce(lower(v_admin1), '')
       and coalesce(lower(city_regency), '') = coalesce(lower(v_city), '');

    if v_location_id is null then
      insert into public.phase3_locations (
        country_iso3, admin1, city_regency, latitude, longitude, coordinate_precision
      )
      values (v_country, v_admin1, v_city, v_latitude, v_longitude, v_coord_prec)
      returning id into v_location_id;
    end if;

    insert into public.phase3_event_locations (event_id, location_id)
    values (v_event_id, v_location_id)
    on conflict do nothing;
  end loop;

  return v_event_id;
end;
$$;

