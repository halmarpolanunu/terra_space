create table if not exists public.phase3_event_sources (
  event_id          uuid not null references public.phase3_events (id) on delete cascade,
  phase1_source_id  uuid not null references public.phase1_sources (id) on delete restrict,
  reference_label   text not null,
  evidence_quote    text,
  created_at        timestamptz not null default now(),
  primary key (event_id, phase1_source_id)
