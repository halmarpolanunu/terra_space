create table if not exists public.phase3_events (
  id                        uuid primary key default gen_random_uuid(),
  candidate_key             text unique,
  phase1_source_id          uuid references public.phase1_sources (id) on delete restrict,
  origin                    text not null
                              constraint phase3_events_origin_check
                              check (origin in ('pipeline', 'manual')),
  pipeline_outcome          text
                              constraint phase3_events_pipeline_outcome_check
                              check (pipeline_outcome is null or pipeline_outcome in ('FINAL', 'EXCEPTION')),
  dashboard_status          text not null default 'published'
                              constraint phase3_events_dashboard_status_check
                              check (dashboard_status in (
                                'published', 'hidden', 'rejected', 'archived', 'merged'
                              )),
  title                     text not null,
  summary                   text not null,
  event_date                text,
  event_date_precision      text
                              constraint phase3_events_event_date_precision_check
                              check (event_date_precision is null
                                     or event_date_precision in ('exact', 'month', 'year', 'unknown')),
  epistemic_status          text not null
                              constraint phase3_events_epistemic_status_check
                              check (epistemic_status in (
                                'confirmed', 'reported', 'alleged', 'planned', 'denied', 'unknown'
                              )),
  event_type_id             uuid references public.phase3_event_types (id) on delete set null,
  pipeline_candidate        jsonb,
  pipeline_event_snapshot   jsonb,
  pipeline_first_seen_at    timestamptz,
  human_modified_at         timestamptz,
  human_modified_fields     jsonb not null default '[]'::jsonb
                              constraint phase3_events_human_modified_fields_is_array
                              check (jsonb_typeof(human_modified_fields) = 'array'),
  published_at              timestamptz,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),
  constraint phase3_events_pipeline_requires_candidate_key
    check (origin <> 'pipeline' or candidate_key is not null),
  constraint phase3_events_pipeline_requires_outcome
    check (origin <> 'pipeline' or pipeline_outcome is not null),
  constraint phase3_events_pipeline_requires_source
    check (origin <> 'pipeline' or phase1_source_id is not null),
  constraint phase3_events_manual_has_no_pipeline_outcome
    check (origin <> 'manual' or pipeline_outcome is null)
);

create table if not exists public.phase3_event_runs (
  run_id                bigint generated by default as identity primary key,
  candidate_key         text not null,
  phase1_source_id      uuid not null references public.phase1_sources (id) on delete restrict,
  attempt_number        integer not null
                          constraint phase3_event_runs_attempt_number_check
                          check (attempt_number in (1, 2)),
  candidate             jsonb not null,
  factual_status        text,
  event_record          jsonb,
  taxonomy_status       text,
  safeguard_status      text,
  safeguard_reasons     jsonb,
  factual_raw_output    text,
  taxonomy_raw_output   text,
  safeguard_raw_output  text,
  error_message         text,
  processed_at          timestamptz not null,
  outcome_payload       jsonb not null,
  created_at            timestamptz not null default now()
